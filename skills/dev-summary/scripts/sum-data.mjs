/** 读信息表：{ basic, text, t(标题) => 行对象数组 } */
export function readSheet(path) {
  const md = readText(path)
  const S = sections(md)
  const byTitle = (title) => {
    const s = S.find((x) => x.title.replace(/^[\d.\s]+/, '').trim() === title) || S.find((x) => x.title.includes(title))
    if (!s) return []
    const own = s.body.split('\n')
    // 只取本节自己的第一张表（不含子节）
    const tb = tables(own.join('\n'))[0]
    return rowsAsObjects(tb).filter((r) => Object.values(r).some((v) => v && !/^(…|\.\.\.|……)$/.test(v)))
  }
  const kv = (title) => Object.fromEntries(byTitle(title).map((r) => [r['项目'], r['内容'] || '']))
  return { md, S, basic: kv('基本信息'), text: kv('其他文字'), third: kv('第三方评测结论'), t: byTitle }
}

