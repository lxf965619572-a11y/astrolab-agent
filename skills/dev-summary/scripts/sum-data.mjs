/** 研制类型：返回 'I' | 'III' | 'IV' | '' */
export function classOf(s) {
  const t = String(s || '').replace(/类/g, '').trim()
  if (/^(Ⅳ|IV|4)$/i.test(t)) return 'IV'
  if (/^(Ⅲ|III|3)$/i.test(t)) return 'III'
  if (/^(Ⅰ|I|1)$/i.test(t)) return 'I'
  if (/^(Ⅱ|II|2)$/i.test(t)) return 'II'
  return ''
}

/** 在目录中找文件（不进 node_modules、.git、runtime、.utest） */
export function findFiles(dir, re, depth = 6) {
  const out = []
  const walk = (d, k) => {
    if (k > depth) return
    let names = []
    try { names = readdirSync(d) } catch { return }
    for (const n of names) {
      if (['node_modules', '.git', 'runtime', '.utest', '.cppcheck', '.dsh'].includes(n)) continue
      const p = join(d, n)
      let st; try { st = statSync(p) } catch { continue }
      if (st.isDirectory()) walk(p, k + 1)
      else if (re.test(n)) out.push(p)
    }
  }
  if (existsSync(dir)) walk(dir, 0)
  return out.sort()
}

